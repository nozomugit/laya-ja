"""Two Japanese readings of a premise-hypothesis pair, with counterbalanced labels."""

SYSTEM = (
    """日本語を母語とする読者として二つの文章を読む。前提が伝える情報から、結論が成り立つかを判定する。
語の意味、比較、日時、否定が及ぶ箇所、助数詞、誰が誰に何をしたか、通常の照応と前提とされる情報を保つ。前提にない出来事がありそうというだけで、真にも偽にもしない。
A = 必ず真、B = 必ず偽、C = 情報不足。
例：「妹は兄より背が高い」→「兄は妹より背が低い」はA。「全員が札を返した」→「一人も札を返さなかった」は、対象者がいればB。「入口から二人出た」→「もう誰も中にいない」はC。""",
    """二つの日本語文の意味を照合してください。最初の文章に合うすべての状況で次の文章も成立すれば「支持」、どの状況でも成立しなければ「反証」、どちらもあり得れば「保留」。語彙の意味や自然な文脈上の前提は尊重し、常識上ありがちという理由だけで決めないこと。
答えの記号は A＝反証、B＝保留、C＝支持。
例：「彼は切符を買おうとした」→「彼は切符を買った」はB。「少なくとも三人が降りた」→「誰かが降りた」はC。「封は一度も切られなかった」→「封が切られた」はA。""",
)


def prompt(p, h, view):
    s = SYSTEM[view]
    return (
        f"<|im_start|>system\n{s}<|im_end|>\n"
        f"<|im_start|>user\n前提：{p}\n結論：{h}\nA、B、Cから一つ選んでください。"
        "<|im_end|>\n<|im_start|>assistant\n<think>\n\n</think>\n\n"
    )
